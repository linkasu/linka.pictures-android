#!/usr/bin/env python3
"""Generate pinned Unicode 16.0 grapheme data; Python standard library only."""

import argparse
import hashlib
from pathlib import Path
import tempfile
import urllib.request


VERSION = "16.0.0"
BASE = "https://www.unicode.org/Public/16.0.0/ucd/"
# SHA-256 pins both the Unicode version and exact upstream bytes.
SOURCES = {
    "GraphemeBreakProperty.txt": (BASE + "auxiliary/GraphemeBreakProperty.txt", "c29360bd6f7132811d701d29069541e827eb44bfc4c8fbde8c370d6982689dc1"),
    "GraphemeBreakTest.txt": (BASE + "auxiliary/GraphemeBreakTest.txt", "ee2b9354d270ac061b29f09662cafea06341d77e704b8cc6bd72aaeeda363cb5"),
    "emoji-data.txt": (BASE + "emoji/emoji-data.txt", "f1365a5173eee18e1f98b240cdc492e84a25f1ce7e0c9d1094eb29c41a22696a"),
    "DerivedCoreProperties.txt": (BASE + "DerivedCoreProperties.txt", "39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd"),
    "LICENSE.txt": ("https://www.unicode.org/license.txt", "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96"),
}
GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT"]
INCB = ["None", "Consonant", "Linker", "Extend"]
ROOT = Path(__file__).resolve().parent.parent
MAIN = "shared/src/commonMain/kotlin/su/linka/pictures/text/"
TEST = "shared/src/commonTest/kotlin/su/linka/pictures/text/"


def load(cache):
    result = {}
    for name, (url, digest) in SOURCES.items():
        path = cache / name
        if path.exists():
            if path.stat().st_size > 4_000_000:
                raise ValueError(f"Oversize cache: {name}")
            data = path.read_bytes()
        else:
            with urllib.request.urlopen(url, timeout=40) as response:
                if response.status != 200 or response.url != url:
                    raise ValueError(f"Unexpected HTTP response: {url}: {response.status}, {response.url}")
                data = response.read(4_000_001)
            if len(data) > 4_000_000:
                raise ValueError(f"Oversize response: {url}")
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError(f"SHA-256 mismatch: {url}")
        text = data.decode("utf-8")
        if name in ("GraphemeBreakProperty.txt", "GraphemeBreakTest.txt", "DerivedCoreProperties.txt"):
            assert text.startswith(f"# {name[:-4]}-{VERSION}.txt\n"), name
        elif name == "emoji-data.txt":
            assert "# Used with Emoji Version 16.0 " in text[:1000]
        else:
            assert text.startswith("UNICODE LICENSE V3\n")
        if not path.exists():
            path.write_bytes(data)
        result[name] = text
    return result


def ranges(text, properties, incb=False):
    rows = []
    for line in text.splitlines():
        fields = [field.strip() for field in line.split("#")[0].split(";")]
        if len(fields) < 2:
            continue
        if incb:
            if fields[1] != "InCB":
                continue
            assert len(fields) == 3 and fields[2] in properties, fields
            prop = fields[2]
        else:
            prop = fields[1]
            if prop not in properties:
                continue
        ends = fields[0].split("..")
        start, end = int(ends[0], 16), int(ends[-1], 16)
        assert 0 <= start <= end <= 0x10FFFF
        rows.append((start, end, properties.index(prop)))
    compact = []
    for start, end, prop in sorted(rows):
        if compact:
            assert compact[-1][1] < start, (compact[-1], start)
            if compact[-1][1] + 1 == start and compact[-1][2] == prop:
                compact[-1] = (compact[-1][0], end, prop)
                continue
        compact.append((start, end, prop))
    assert {prop for _, _, prop in compact} == set(range(1, len(properties)))
    return compact


def value(rows, point):
    return next((prop for start, end, prop in rows if start <= point <= end), 0)


def header(source, texts):
    # Keep the upstream header, including all copyright and license notices.
    lines = []
    for line in texts[source].splitlines():
        if not line.startswith("#"):
            break
        lines.append("//" + line[1:].rstrip())
    return "\n".join(lines) + "\n// Generated by scripts/generate-grapheme-tables.py; do not edit.\n// License: third_party/unicode/LICENSE.txt\n"


def generate(texts):
    gcb = ranges(texts["GraphemeBreakProperty.txt"], GCB)
    ep = ranges(texts["emoji-data.txt"], ["None", "Extended_Pictographic"])
    incb = ranges(texts["DerivedCoreProperties.txt"], INCB, incb=True)
    for point, prop in [(0xD, "CR"), (0xA, "LF"), (0x301, "Extend"), (0x200D, "ZWJ"), (0x1F1E6, "Regional_Indicator"), (0xAC00, "LV"), (0xAC01, "LVT")]:
        assert value(gcb, point) == GCB.index(prop)
    assert value(gcb, 0xD800) == 0 and value(ep, 0x1F469) == 1
    assert value(incb, 0x915) == 1 and value(incb, 0x94D) == 2 and value(incb, 0x301) == 3
    tables = header("GraphemeBreakProperty.txt", texts)
    tables += header("emoji-data.txt", texts) + header("DerivedCoreProperties.txt", texts)
    tables += "\npackage su.linka.pictures.text\n\ninternal object GraphemeTables {\n"
    tables += "    // GCB IDs: " + ", ".join(f"{i}={name}" for i, name in enumerate(GCB)) + "\n"
    tables += "    // InCB IDs: " + ", ".join(f"{i}={name}" for i, name in enumerate(INCB)) + "\n"
    tables += "    // Sorted inclusive start/end/property triples; absent code points have property 0.\n"
    for name, rows in [("gcb", gcb), ("extendedPictographic", ep), ("incb", incb)]:
        tables += f"    val {name} = intArrayOf(\n"
        tables += "".join(f"        0x{start:X}, 0x{end:X}, {prop},\n" for start, end, prop in rows)
        tables += "    )\n"
    tables += "}\n"
    vectors = [line.split("#")[0].strip() for line in texts["GraphemeBreakTest.txt"].splitlines() if line.split("#")[0].strip()]
    assert len(vectors) == 1093
    for vector in vectors:
        tokens = vector.split()
        assert tokens[0] == tokens[-1] == "÷" and len(tokens) % 2 == 1
        assert all(token in ("÷", "×") for token in tokens[::2])
        assert all(0 <= int(token, 16) <= 0x10FFFF for token in tokens[1::2])
    tests = header("GraphemeBreakTest.txt", texts) + "\npackage su.linka.pictures.text\n\ninternal val graphemeBreakVectors = arrayOf(\n"
    tests += "".join(f'    "{vector}",\n' for vector in vectors) + ")\n"
    print(f"Unicode {VERSION}: {len(gcb)} GCB, {len(ep)} EP, {len(incb)} InCB ranges; {len(vectors)} vectors")
    return {MAIN + "GraphemeTables.kt": tables, TEST + "GraphemeBreakVectors.kt": tests, "third_party/unicode/LICENSE.txt": texts["LICENSE.txt"]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify checked-in bytes without changing outputs")
    parser.add_argument("--cache-dir", type=Path, help="Reuse only this explicit source cache (all bytes verified)")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="unicode-16-grapheme-") as temporary:
        cache = args.cache_dir if args.cache_dir else Path(temporary)
        cache.mkdir(parents=True, exist_ok=True)
        for relative, text in generate(load(cache)).items():
            path = ROOT / relative
            data = text.encode("utf-8")
            if args.check:
                if not path.exists() or path.read_bytes() != data:
                    raise SystemExit(f"Generated file differs: {relative}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)


if __name__ == "__main__":
    main()
